#!/usr/bin/env python3
"""Regenerate the R2-D2 prior-family study's thesis tables from an analysis snapshot.

    python regen_study_tables.py                     # write docs/thesis/tables/study_*.tex
    python regen_study_tables.py --check             # regenerate into a temp dir and diff against
                                                     # the committed study_*.tex; exit 1 on any
                                                     # difference
    python regen_study_tables.py --snapshot <dir>    # read <dir>/tables/*.csv instead of
                                                     # sagp_analysis/r2d2/latest

Plan Q9: `regen_tables.py`'s contract is that every number comes from `synthobj` itself, so the
study's tables get this separate script, whose contract is that every number comes from the study's
analysis outputs: the snapshot's `tables/*.csv` (written by its `analyze.py`), stage 0's calibration
table and G0 decision (`sagp_analysis/2026-09-25-r2d2-prior/`), and, for the cost table's
GPU-sharing column, the packed launcher's work lists under `slurm/work/`. No number is typed here.

Each fragment is a whole `table` float whose caption names the snapshot directory it was read from
and the scope it covers (families, seeds and run counts, read from the snapshot's `inventory.csv`),
so a pilot-scope table cannot be mistaken for the final one. Numbers are formatted only; nothing is
re-estimated. The statistic that averages over (family, seed) units is called seed-averaged.

Only numpy-free standard-library code: `csv`, `re`, `pathlib`.
"""
