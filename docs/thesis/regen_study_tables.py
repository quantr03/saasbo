TABLE_REGISTRY = [
    ("study_final_regret.tex", study_final_regret),
    ("study_effects.tex", study_effects),
    ("study_twins.tex", study_twins),
    ("study_identification.tex", study_identification),
    ("study_diagnostics_cost.tex", study_diagnostics_cost),
    ("study_calibration.tex", study_calibration),
]


def generate_all(snap: Snapshot, outdir: Path) -> None:
    outdir.mkdir(parents=True, exist_ok=True)
    for filename, fn in TABLE_REGISTRY:
        fn(snap, outdir)
    print(f"regen_study_tables: {len(TABLE_REGISTRY)} table(s) from snapshot {snap.name} written to {outdir}")


def run_check(snap: Snapshot, tables_dir: Path) -> int:
    with tempfile.TemporaryDirectory(prefix="study_tables_check_") as tmp:
        fresh_dir = Path(tmp)
        generate_all(snap, fresh_dir)
        mismatches = []
        for name, _fn in TABLE_REGISTRY:
            committed, fresh = tables_dir / name, fresh_dir / name
            a = committed.read_text(encoding="utf-8").splitlines(keepends=True) if committed.exists() else []
            b = fresh.read_text(encoding="utf-8").splitlines(keepends=True)
            d = list(difflib.unified_diff(a, b, fromfile=str(committed), tofile=str(fresh)))
            if d:
                mismatches.append((name, d))
    if mismatches:
        for name, d in mismatches:
            print(f"=== {name} differs ===")
            sys.stdout.writelines(d)
        print(f"regen_study_tables --check: {len(mismatches)} of {len(TABLE_REGISTRY)} table(s) differ: "
              + ", ".join(name for name, _ in mismatches))
        return 1
    print(f"regen_study_tables --check: {len(TABLE_REGISTRY)} tables current")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="regenerate into a temp dir and diff")
    parser.add_argument("--snapshot", type=Path, default=DEFAULT_SNAPSHOT,
                        help="analysis snapshot directory (default: sagp_analysis/r2d2/latest)")
    parser.add_argument("--tables-dir", type=Path, default=TABLES_DIR,
                        help="where the fragments are written, or diffed against with --check "
                             "(default: docs/thesis/tables)")
    args = parser.parse_args(argv)
    snap = Snapshot(args.snapshot)
    if args.check:
        return run_check(snap, args.tables_dir)
    generate_all(snap, args.tables_dir)
    return 0


if __name__ == "__main__":
    sys.exit(main())
