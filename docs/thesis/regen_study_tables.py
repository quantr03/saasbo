# =================================================================================================
# Reading
# =================================================================================================


def read_csv(path: Path) -> list[dict[str, str]]:
    with path.open(newline="", encoding="utf-8") as fh:
        return list(csv.DictReader(fh))


def fnum(s: str) -> float:
    """A CSV cell as a float; an empty cell or 'nan' as NaN."""
    return float(s) if s not in ("", None) else math.nan


class Snapshot:
    """One analysis snapshot: its resolved directory name, its tables, and its scope."""

    def __init__(self, path: Path):
        self.path = path.resolve()
        self.name = self.path.name
        self.tables = self.path / "tables"
        if not self.tables.is_dir():
            raise SystemExit(f"regen_study_tables: no tables/ under {self.path}")
        self.inventory = read_csv(self.tables / "inventory.csv")
        self.summary = read_csv(self.tables / "inventory_summary.csv")
        self.methods = [r["method"] for r in self.summary]  # the analysis's own method order
        regret_files = sorted(self.tables.glob("final_regret_t*.csv"))
        if len(regret_files) != 1:
            raise SystemExit(f"regen_study_tables: expected one final_regret_t*.csv, found {regret_files}")
        self.regret_file = regret_files[0]
        self.t_final = int(re.fullmatch(r"final_regret_t(\d+)\.csv", self.regret_file.name).group(1))

    def csv(self, name: str) -> list[dict[str, str]]:
        return read_csv(self.tables / name)

    def scope(self) -> str:
        """Families, seeds and run counts covered, in words, from inventory.csv/inventory_summary.csv."""
        fam_seeds: dict[str, set[int]] = {}
        for r in self.inventory:
            fam_seeds.setdefault(r["family"], set()).add(int(r["seed"]))
        families = sorted(fam_seeds)
        seed_sets = {frozenset(s) for s in fam_seeds.values()}
        if len(seed_sets) == 1:
            seeds = "seeds " + seed_ranges(next(iter(seed_sets)))
            fam_part = f"{len(families)} famil{'y' if len(families) == 1 else 'ies'} ({join_words([code(f) for f in families])}), {seeds}"
        else:
            fam_part = f"{len(families)} families: " + "; ".join(
                f"{code(f)} seeds {seed_ranges(fam_seeds[f])}" for f in families
            )
        n_runs = sum(int(r["runs"]) for r in self.summary)
        n_complete = sum(int(r["complete"]) for r in self.summary)
        return (
            f"snapshot {code(self.name)} (scope: {fam_part}; {len(self.methods)} methods, "
            f"{n_complete} of {n_runs} runs complete)"
        )


def seed_ranges(seeds) -> str:
    s = sorted(seeds)
    parts, start, prev = [], s[0], s[0]
    for x in s[1:] + [None]:
        if x is not None and x == prev + 1:
            prev = x
            continue
        parts.append(str(start) if start == prev else f"{start}--{prev}")
        if x is not None:
            start = prev = x
    return ", ".join(parts)


def join_words(items: list[str]) -> str:
    if len(items) <= 2:
        return " and ".join(items)
    return ", ".join(items[:-1]) + " and " + items[-1]


# =================================================================================================
# Formatting
# =================================================================================================


def esc(s: str) -> str:
    return s.replace("_", r"\_").replace("%", r"\%")


def code(s: str) -> str:
    return r"\SOcode{" + esc(s) + "}"


def row(cells: list[str]) -> str:
    return " & ".join(cells) + r" \\"


def g3(x: float) -> str:
    """Three significant figures, as the analysis's own .md tables print them; NaN as ---."""
    if math.isnan(x):
        return "---"
    if x != 0 and abs(x) < 1e-3:
        return f"{x:.2e}"
    s = f"{x:.3g}"
    if "e" in s:
        s = f"{x:.0f}"
    if s.startswith("-") and float(s) == 0.0:
        s = s[1:]
    return s


def f3(x: float) -> str:
    """Fixed three decimals, for log10 differences; NaN as ---; no negative zero."""
    if math.isnan(x):
        return "---"
    s = f"{x:.3f}"
    if s.startswith("-") and float(s) == 0.0:
        s = s[1:]
    return s


def interval(lo: float, hi: float, fmt=f3) -> str:
    return f"[{fmt(lo)}, {fmt(hi)}]"


def method_cell(method: str) -> str:
    """A cell as its structure and parameterization initials (`additive-lengthscale_r2d2` -> AL);
    a reference method by its own name. The prior family is shown beside it, never in the label."""
    if "-" not in method:
        return code(method)
    structure, parameterization = method.split("-", 1)
    return (structure[0] + parameterization[0]).upper()


CELL_NAMING = ("Cells are named by two initials, structure then parameterization: A or P for "
               "additive or product, then A or L for amplitude or lengthscale.")


def hd(*lines: str) -> str:
    """A column heading stacked over several lines, so a wide table fits the text block."""
    return lines[0] if len(lines) == 1 else r"\shortstack{" + r"\\ ".join(lines) + "}"


def write_table(path: Path, comment: list[str], caption: str, label: str, body: list[str],
                size: str = r"\scriptsize", sep: str = "3pt") -> None:
    lines = [GENERATED_HEADER, *(f"% {c}" for c in comment),
             r"\begin{table}[tbp]", r"\centering",
             r"\caption{" + caption + r"}\label{" + label + "}",
             size + r"\setlength{\tabcolsep}{" + sep + "}",
             *body, r"\end{table}"]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def interval_levels(header: list[str]) -> list[int]:
    """The interval levels the CSV carries, read off its lo<level> columns (e.g. [90, 95])."""
    return sorted(int(m.group(1)) for h in header if (m := re.fullmatch(r"lo(\d+)", h)))


