def study_final_regret(snap: Snapshot, outdir: Path) -> None:
    rows = read_csv(snap.regret_file)
    families = sorted({r["family"] for r in rows})
    by = {(r["family"], r["method"]): r for r in rows}
    prior = {r["method"]: r["prior_family"] for r in rows}
    n_per = sorted({int(r["n"]) for r in rows})
    groups: list[tuple[str, list[str]]] = []  # (prior family, its methods), the analysis's order
    for m in snap.methods:
        if groups and groups[-1][0] == prior[m]:
            groups[-1][1].append(m)
        else:
            groups.append((prior[m], [m]))
    cols = "l" + "".join("r" * len(ms) for _p, ms in groups)
    group_row, rules, c0 = ["objective"], [], 2
    for p, ms in groups:
        group_row.append(r"\multicolumn{" + str(len(ms)) + "}{c}{" + PRIOR_NAMES[p] + "}")
        rules.append(r"\cmidrule(lr){" + f"{c0}-{c0 + len(ms) - 1}" + "}")
        c0 += len(ms)
    body = [r"\begin{tabular}{" + cols + "}", r"\toprule", row(group_row), "".join(rules),
            row(["family", *[method_cell(m) for m in snap.methods]]), r"\midrule"]
    for f in families:
        cells = []
        for m in snap.methods:
            r = by.get((f, m))
            if r is None:
                cells.append("---")
            elif r["rank_in_family"] == "1":
                cells.append(r"\textbf{" + g3(fnum(r["median"])) + "}")
            else:
                cells.append(g3(fnum(r["median"])))
        body.append(row([code(f), *cells]))
    body += [r"\bottomrule", r"\end{tabular}"]
    caption = (
        f"Final simple regret at iteration {snap.t_final} by method and objective family: the median "
        f"over seeds ({join_words([str(n) for n in n_per])} per entry), the lowest in each family in "
        f"bold. {CELL_NAMING} "
        f"The quartiles, the ranks within family and the mean rank within seed are in the snapshot's "
        f"{code(snap.regret_file.name)}. Read from {snap.scope()}."
    )
    write_table(outdir / "study_final_regret.tex", [f"source: {snap.regret_file.name}"],
                caption, "app:so:study:tab:regret", body, sep="1.5pt")


