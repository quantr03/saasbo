_EFFECT_ROWS = [  # (effect id in effects_pooled.csv, effect label, prior family label)
    ("S_HC", "structure", "half-Cauchy"),
    ("S_R2D2", "structure", "R2-D2"),
    ("dS", "structure", "difference"),
    ("P_HC", "parameterization", "half-Cauchy"),
    ("P_R2D2", "parameterization", "R2-D2"),
    ("dP", "parameterization", "difference"),
]


def study_effects(snap: Snapshot, outdir: Path) -> None:
    path = snap.tables / "effects_pooled.csv"
    rows = read_csv(path)
    header = list(rows[0].keys())
    levels = interval_levels(header)
    by = {r["effect"]: r for r in rows}
    body = [r"\begin{tabular}{llrr" + "c" * len(levels) + "l}", r"\toprule",
            row(["effect", hd("prior", "family"), "median", hd("seed-", "averaged"),
                 *[hd(f"{lv}\\%", "interval") for lv in levels], hd("PR2", "reading")]), r"\midrule"]
    for i, (eid, eff, fam) in enumerate(_EFFECT_ROWS):
        if i == 3:
            body.append(r"\midrule")
        r = by[eid]
        body.append(row([eff, fam, f3(fnum(r["median"])), f3(fnum(r["mean"])),
                         *[interval(fnum(r[f"lo{lv}"]), fnum(r[f"hi{lv}"])) for lv in levels],
                         r["pr2_reading"] or "---"]))
    body += [r"\bottomrule", r"\end{tabular}"]
    n_boot = sorted({r["n_boot"] for r in rows})
    n_units = sorted({by[eid]["n_units"] for eid, _e, _f in _EFFECT_ROWS})
    caption = (
        f"The two main effects on the base-10 logarithm of final regret at iteration {snap.t_final}, "
        f"by prior family, and their differences (R2-D2 minus half-Cauchy). Structure is additive "
        f"minus product and parameterization is amplitude minus lengthscale, each averaged over the "
        f"other factor within one (family, seed) unit; negative means lower regret for additive, or "
        f"for amplitude. Median and seed-averaged value over the {join_words(n_units)} units; the intervals are percentile "
        f"intervals of the seed-averaged value from a (family, seed)-cluster bootstrap with "
        f"{join_words(n_boot)} resamples. The PR2 reading compares the {levels[0]}\\% interval of each "
        f"difference with the preregistered equivalence band. Read from {snap.scope()}."
    )
    write_table(outdir / "study_effects.tex", [f"source: {path.name} (main_HC, main_R2D2, interaction rows)"],
                caption, "app:so:study:tab:effects", body)


