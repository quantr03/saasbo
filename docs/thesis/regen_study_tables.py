# 3. The twin pairs, Delta_c per cell
# =================================================================================================


def study_twins(snap: Snapshot, outdir: Path) -> None:
    pooled_path = snap.tables / "effects_pooled.csv"
    fam_path = snap.tables / "pr3_twin_medians.csv"
    pooled = [r for r in read_csv(pooled_path) if r["kind"] == "twin"]
    levels = interval_levels(list(pooled[0].keys()))
    per_fam = read_csv(fam_path)
    families = sorted({r["family"] for r in per_fam})
    pf = {(r["family"], r["effect"]): r for r in per_fam}
    cells = [m for m in snap.methods if f"Delta_{m}" in {r["effect"] for r in pooled}]
    by = {r["effect"]: r for r in pooled}
    body = [r"\begin{tabular}{lrrr" + "c" * len(levels) + "}", r"\toprule",
            row(["R2-D2 cell", "units", "median", hd("seed-", "averaged"),
                 *[hd(f"{lv}\\%", "interval") for lv in levels]]),
            r"\midrule"]
    for m in cells:
        r = by[f"Delta_{m}"]
        body.append(row([method_cell(m), r["n_units"], f3(fnum(r["median"])), f3(fnum(r["mean"])),
                         *[interval(fnum(r[f"lo{lv}"]), fnum(r[f"hi{lv}"])) for lv in levels]]))
    body += [r"\bottomrule", r"\end{tabular}", r"\par\medskip",
             r"\begin{tabular}{l" + "r" * len(cells) + "}", r"\toprule",
             row(["family", *[method_cell(m) for m in cells]]), r"\midrule"]
    any_fail = False
    for f in families:
        fam_cells = []
        for m in cells:
            q = pf.get((f, f"Delta_{m}"))
            if q is None:
                fam_cells.append("---")
                continue
            mark = "" if q["holds"] == "True" else "*"
            any_fail |= bool(mark)
            fam_cells.append(f3(fnum(q["median"])) + mark)
        body.append(row([code(f), *fam_cells]))
    body += [r"\bottomrule", r"\end{tabular}"]
    n_per = sorted({r["n"] for r in per_fam})
    caption = (
        f"Twin pairs: the difference in the base-10 logarithm of final regret at iteration "
        f"{snap.t_final}, each R2-D2 cell minus its half-Cauchy twin on the same (family, seed); "
        f"positive means higher regret under R2-D2. Upper block, over all units: median, "
        f"seed-averaged value and its (family, seed)-cluster bootstrap percentile intervals. Lower "
        f"block, per family: the median over that family's seeds ({join_words(n_per)} pairs each, "
        f"{code(fam_path.name)})"
        + ("; an asterisk marks a cell and family where the PR3 null does not hold." if any_fail
           else "; the PR3 null holds in every cell and family.")
        + f" {CELL_NAMING} Read from {snap.scope()}."
    )
    write_table(outdir / "study_twins.tex", [f"source: {pooled_path.name} (twin rows), {fam_path.name}"],
                caption, "app:so:study:tab:twins", body)


