def study_identification(snap: Snapshot, outdir: Path) -> None:
    path = snap.tables / "identification_by_prior_family.csv"
    pr4_path = snap.tables / "pr4_identification_twin_pairs.csv"
    rows = read_csv(path)
    pr4 = read_csv(pr4_path)
    levels = interval_levels(list(pr4[0].keys()))
    body = [r"\begin{tabular}{llrrrrrrr}", r"\toprule",
            row(["cell", "prior", "runs", hd("AP native", "mean"),
                 hd("AP native", "median"), hd("AP Sobol", "mean"), hd("AP Sobol", "median"),
                 hd("F1", "mean"), hd("predicted", "active", "(median)")]), r"\midrule"]
    prev = None
    for r in rows:
        key = (r["structure"], r["parameterization"])
        if prev is not None and key != prev:
            body.append(r"\addlinespace")
        prev = key
        body.append(row([method_cell(f"{r['structure']}-{r['parameterization']}"), PRIOR_NAMES[r["prior_family"]],
                         r["n_runs"], f3(fnum(r["ap_native_mean"])), f3(fnum(r["ap_native_median"])),
                         f3(fnum(r["ap_sobol_mean"])), f3(fnum(r["ap_sobol_median"])),
                         f3(fnum(r["f1_mean"])), g3(fnum(r["n_pred_active_median"]))]))
    body += [r"\bottomrule", r"\end{tabular}", r"\par\medskip",
             r"\begin{tabular}{llrrr" + "c" * len(levels) + "l}", r"\toprule",
             row(["R2-D2 cell", "metric", "pairs", hd("mean", "difference"), hd("median", "difference"),
                  *[hd(f"{lv}\\%", "interval") for lv in levels], hd("PR4", "reading")]), r"\midrule"]
    for r in pr4:
        metric = {"ap_native": "AP native", "ap_sobol": "AP Sobol"}.get(r["metric"], esc(r["metric"]))
        body.append(row([method_cell(r["cell"]), metric, r["n_pairs"], f3(fnum(r["mean_diff"])),
                         f3(fnum(r["median_diff"])),
                         *[interval(fnum(r[f"lo{lv}"]), fnum(r[f"hi{lv}"])) for lv in levels],
                         r["reading"]]))
    body += [r"\bottomrule", r"\end{tabular}"]
    caption = (
        f"Identification of the active coordinates by cell and prior family, scored at each run's "
        f"last readout. Upper block: average precision of ranking the coordinates by the posterior "
        f"median of the cell's own sparsity parameter (native) and by the estimated Sobol' index, "
        f"the F1 score of the predicted active set at the analysis's activity threshold, and the "
        f"median size of that set, over the complete runs ({code(path.name)}). Lower block: each R2-D2 cell minus its half-Cauchy "
        f"twin on the same (family, seed), with the (family, seed)-cluster bootstrap percentile "
        f"interval of the median paired difference and the PR4 reading against the preregistered "
        f"equivalence band ({code(pr4_path.name)}). {CELL_NAMING} Read from {snap.scope()}."
    )
    write_table(outdir / "study_identification.tex", [f"source: {path.name}, {pr4_path.name}"],
                caption, "app:so:study:tab:identification", body)


