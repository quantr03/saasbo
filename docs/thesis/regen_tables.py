"""Regenerate every table and prose number in the synthobj thesis appendix from the package itself.

Run from docs/thesis/ (the Makefile's `tables`/`check` targets do this):

    python regen_tables.py            # write docs/thesis/tables/*.tex
    python regen_tables.py --check    # regenerate into a temp dir and diff against the committed
                                       # tables/*.tex; exit 1 on any difference

This script is the appendix's single source of numerical truth (task-2 brief): every number that
appears in a table, or that a later fragment quotes in prose via a \\SOnum... macro, is computed
here from `synthobj` itself -- never copied from a test file, a docstring or the decision ledger.
It never reads or writes `data/` (a git-ignored build artifact); every objective it needs is built
in-process with `synthobj.make_family`/`synthobj.families.build`.

Structure: one function per table (`TABLE_REGISTRY` below lists them in the brief's order), each
with signature `fn(outdir: Path, stats: dict) -> None`. A function writes its own file under
`outdir` and may stash a number into the shared `stats` dict for a later table (`numbers.tex`) to
read -- `tab_grid_summary` and `tab_quadrature_gap` do this for the two worst-case figures
`numbers.tex` quotes. `get_grid100()` builds the 14 x 10 = 140 objective D=100 study grid once
(memoized at module scope) and every table that needs it shares that one build.
"""
