def tab_labels_fields(outdir: Path, stats: dict) -> None:
    import dataclasses

    field_names = [f.name for f in dataclasses.fields(Labels)]
    have, want = set(field_names), set(_LABELS_MEANING)
    if have != want:
        raise RuntimeError(
            "tab_labels_fields: _LABELS_MEANING is out of sync with dataclasses.fields(Labels): "
            f"missing from dict: {sorted(have - want)}; stale entries in dict: {sorted(want - have)}"
        )

    lines = [
        r"\begin{tabular}{lllp{6.5cm}}",
        r"\toprule",
        row(["field", "type", "shape", "meaning"]),
        r"\midrule",
    ]
    for f in dataclasses.fields(Labels):
        shape, meaning = _LABELS_MEANING[f.name]
        lines.append(row([code(f.name), code(f.type), shape, meaning]))
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_generated(outdir / "tab_labels_fields.tex", [], lines)


