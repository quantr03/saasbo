def families_ell_set() -> list[float]:
    """Every distinct lengthscale any `FAMILIES` entry uses (its own default spec, D-independent)."""
    ells: set[float] = set()
    for factory in FAMILIES.values():
        spec = factory()
        if isinstance(spec.ells, (int, float)):
            ells.add(float(spec.ells))
        else:
            ells.update(float(e) for e in spec.ells)
    return sorted(ells)


def v_ell_union() -> list[float]:
    """Union of `tests/test_kernel.py`'s `V_REFERENCE` keys with `families_ell_set()`."""
    ells = {float(k) for k in V_REFERENCE.keys()}
    ells.update(families_ell_set())
    return sorted(ells)


