_SLOPE_RATIO_N = 2000
_SLOPE_RATIO_SEED = 12345
_SLOPE_RATIO_GRID_N = 1024


def tab_slope_ratio(outdir: Path, stats: dict) -> None:
    ells = families_ell_set()
    grid = kernel.make_grid(0.0, 1.0, _SLOPE_RATIO_GRID_N)

    lines = [
        f"% N = {_SLOPE_RATIO_N} draws per ell, default_rng({_SLOPE_RATIO_SEED}) fresh per ell, "
        f"1024-point unit grid; SE = sample std / sqrt(N)",
        r"\begin{tabular}{rrrrr}",
        r"\toprule",
        row([r"$\ell$", r"$5/(3\ell^2\vell{\ell})$", "raw-draw mean $\\pm$ SE", "rescaled mean $\\pm$ SE",
             "ratio (rescaled/theory)"]),
        r"\midrule",
    ]
    for ell in ells:
        F = kernel.eigen_factor(0.0, 1.0, _SLOPE_RATIO_GRID_N, ell)
        rng = np.random.default_rng(_SLOPE_RATIO_SEED)
        theory = 5.0 / (3.0 * ell**2 * kernel.v(ell))
        raw_energies = np.empty(_SLOPE_RATIO_N)
        rescaled_energies = np.empty(_SLOPE_RATIO_N)
        for k in range(_SLOPE_RATIO_N):
            raw_draw = draws.gp_draw(F, rng)
            node_values = raw_draw[-kernel.GL_NODES.size:]
            var_raw = kernel.nu_var(node_values)
            raw_energies[k] = Component.from_raw(0, ell, var_raw, grid, raw_draw, sign=1.0).slope_energy()
            rescaled_energies[k] = Component.from_raw(0, ell, 1.0, grid, raw_draw, sign=1.0).slope_energy()
        raw_mean, raw_se = raw_energies.mean(), raw_energies.std(ddof=1) / math.sqrt(_SLOPE_RATIO_N)
        res_mean, res_se = rescaled_energies.mean(), rescaled_energies.std(ddof=1) / math.sqrt(_SLOPE_RATIO_N)
        ratio = res_mean / theory
        lines.append(row([
            f"{ell:.2f}", f"{theory:.4f}",
            f"{raw_mean:.4f} $\\pm$ {raw_se:.4f}", f"{res_mean:.4f} $\\pm$ {res_se:.4f}", f"{ratio:.4f}",
        ]))
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_generated(outdir / "tab_slope_ratio.tex", [], lines)


