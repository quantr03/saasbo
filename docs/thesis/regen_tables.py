_grid100_cache: dict[tuple[str, int], SyntheticObjective] | None = None
_grid100_build_seconds: float | None = None


def get_grid100() -> dict[tuple[str, int], SyntheticObjective]:
    """The full STUDY_GRID x seeds-0-9 grid at D=100, built once and memoized for this process."""
    global _grid100_cache, _grid100_build_seconds
    if _grid100_cache is None:
        t0 = time.perf_counter()
        cache: dict[tuple[str, int], SyntheticObjective] = {}
        for variant, _family, _overrides in STUDY_GRID:
            for seed in range(10):
                cache[(variant, seed)] = make_family(variant, seed=seed, D=100)
        _grid100_build_seconds = time.perf_counter() - t0
        _grid100_cache = cache
    return _grid100_cache


def paired_coords(obj: SyntheticObjective) -> set[int]:
    """Every coordinate of `obj` that sits in an interaction pair or a rotation pair."""
    coords = {c for inter in obj.interactions for c in (inter.i, inter.j)}
    if obj.rotation is not None:
        coords |= {c for pair in obj.rotation.pairs for c in pair}
    return coords


