def tab_orthogonality(outdir: Path, stats: dict) -> None:
    grid100 = get_grid100()
    GL_NODES, GL_WEIGHTS = kernel.GL_NODES, kernel.GL_WEIGHTS
    w2 = GL_WEIGHTS[:, None] * GL_WEIGHTS[None, :]

    n_blocks = 0
    max_cond = 0.0
    max_orth = 0.0
    max_var = 0.0
    for variant, _family, _overrides in STUDY_GRID:
        if not variant.startswith("interaction_"):
            continue
        for seed in range(10):
            obj = grid100[(variant, seed)]
            by_coord = {c.coord: c for c in obj.components}
            for inter in obj.interactions:
                if inter.c <= 0.0:
                    continue
                n_blocks += 1
                f_i, f_j = by_coord[inter.i], by_coord[inter.j]
                H = inter(GL_NODES[:, None], GL_NODES[None, :])
                e_given_i = H @ GL_WEIGHTS
                e_given_j = GL_WEIGHTS @ H
                max_cond = max(max_cond, float(np.max(np.abs(e_given_i))), float(np.max(np.abs(e_given_j))))
                fi_vals, fj_vals = f_i(GL_NODES), f_j(GL_NODES)
                orth_i = float((w2 * H * fi_vals[:, None]).sum())
                orth_j = float((w2 * H * fj_vals[None, :]).sum())
                max_orth = max(max_orth, abs(orth_i), abs(orth_j))
                # Var_hat h from H/w2 directly (the same 64-node quadrature the row two cells
                # over already computes on), NOT via Interaction.nu_var() -- that method is the
                # algebraic factorization c**2 * Var(u_i) * Var(u_j), i.e. the identity this row
                # claims to check, not an independent measurement of it (reviewer ruling).
                mean_h = float((w2 * H).sum())
                var_h = float((w2 * H**2).sum() - mean_h**2)
                max_var = max(max_var, abs(var_h - inter.c**2))

    lines = [
        r"\begin{tabular}{lrl}",
        r"\toprule",
        row(["quantity", "blocks", "max value"]),
        r"\midrule",
        row([r"$\max |\Ehat[h \mid x_i]|$", str(n_blocks), ceil_pow10_label(max_cond)]),
        row([r"$\max |\Ehat[h f_i]|$", str(n_blocks), ceil_pow10_label(max_orth)]),
        row([r"$\max |\Varhat h - c^2|$", str(n_blocks), ceil_pow10_label(max_var)]),
        r"\bottomrule",
        r"\end{tabular}",
    ]
    write_generated(outdir / "tab_orthogonality.tex", [], lines)


