def report_manifest_hash_match(grid100: dict) -> None:
    manifest_path = REPO_ROOT / "data" / "objectives" / "manifest.json"
    if not manifest_path.exists():
        print("data/objectives/manifest.json not found; skipping archived-grid hash check")
        return

    manifest = json.loads(manifest_path.read_text())
    entries = manifest.get("entries", [])
    matched = mismatched = skipped = 0
    with tempfile.TemporaryDirectory(prefix="synthobj_manifest_check_") as tmp:
        tmp_path = Path(tmp)
        for i, entry in enumerate(entries):
            variant, seed, D = entry.get("variant"), entry.get("seed"), entry.get("D")
            if D != 100 or (variant, seed) not in grid100:
                skipped += 1
                continue
            obj = grid100[(variant, seed)]
            npz_path, _json_path = obj.save(tmp_path / f"entry{i:04d}")
            fresh_hash = hashlib.sha256(npz_path.read_bytes()).hexdigest()
            if fresh_hash == entry.get("sha256_npz"):
                matched += 1
            else:
                mismatched += 1
    print(
        f"manifest check: {matched} matched, {mismatched} mismatched, {skipped} skipped "
        f"(of {len(entries)} manifest entries; D=100 entries only)"
    )


