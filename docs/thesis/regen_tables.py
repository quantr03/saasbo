def _peak_rss_mib() -> float:
    ru_maxrss = resource.getrusage(resource.RUSAGE_SELF).ru_maxrss
    if platform.system() == "Darwin":
        return ru_maxrss / (1024.0 * 1024.0)  # macOS: bytes
    return ru_maxrss / 1024.0  # Linux: kilobytes


