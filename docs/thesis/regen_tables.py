def _projected_grad_norm(x: np.ndarray, grad: np.ndarray, lo: float = 0.0, hi: float = 1.0, tol: float = 1e-9) -> float:
    """Max-norm of the bound-projected gradient at `x` (matches L-BFGS-B's own `gtol` criterion):
    a component pointing further out of an active bound is zeroed; every other component (interior,
    or pointing back into the box from a bound) counts in full."""
    proj = np.array(grad, dtype=float)
    for k in range(len(x)):
        at_lower = x[k] <= lo + tol
        at_upper = x[k] >= hi - tol
        if at_lower and grad[k] <= 0.0:
            proj[k] = 0.0
        elif at_upper and grad[k] >= 0.0:
            proj[k] = 0.0
    return float(np.max(np.abs(proj)))


_REOPT_OPTIONS = {"ftol": 1e-18, "gtol": 1e-14, "maxiter": 10000}


def _reopt_stats(block_iter) -> tuple[int, int, float, float]:
    """`block_iter` yields (value_and_grad_fn, x0) pairs; returns
    (n_blocks, n_exact_zero_gain, max_gain, max_projected_grad_norm_at_x0).

    `gain` is `vg_fn(result.x)[0] - value0`: `vg_fn` is called fresh at the point L-BFGS-B
    reports, never `-result.fun` (scipy's own tracked value at that point). The two are not
    always bit-identical -- a block was found where `result.x` is bit-identical to `x0` yet
    `-result.fun` differs from a fresh `vg_fn(result.x)` by a ulp, which is scipy's internal
    bookkeeping, not the objective: several of the module's original "non-zero" gains, all
    computed via `-result.fun`, turned out to be exactly this artifact (reviewer finding, fix
    round 1) -- the exact count is `tab_fstar_reopt.tex`'s own `# exact-zero gain` column, before
    and after this fix, not repeated here. `max_gain` starts at `None` and is set from the first
    computed gain rather than seeded at `0.0`: if every real gain happens to be <= 0 (as here),
    flooring at a literal `0.0` would silently misreport the true (negative) worst case as an
    implausible exact zero.
    """
    n = n_exact_zero = 0
    max_gain: float | None = None
    max_proj = 0.0
    for vg_fn, x0 in block_iter:
        n += 1
        value0, grad0 = vg_fn(x0)
        max_proj = max(max_proj, _projected_grad_norm(x0, grad0))

        def negated(p, vg_fn=vg_fn):
            v, g = vg_fn(p)
            return -v, -g

        result = minimize(negated, x0, jac=True, method="L-BFGS-B",
                           bounds=[(0.0, 1.0), (0.0, 1.0)], options=_REOPT_OPTIONS)
        reopt_value = float(vg_fn(np.asarray(result.x))[0])
        gain = reopt_value - value0
        if gain == 0.0:
            n_exact_zero += 1
        max_gain = gain if max_gain is None else max(max_gain, gain)
    return n, n_exact_zero, max_gain if max_gain is not None else 0.0, max_proj


