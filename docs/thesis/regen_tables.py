# =================================================================================================
# Formatting helpers
# =================================================================================================


def esc(s: str) -> str:
    """Escape a plain Python identifier for LaTeX text/texttt use (our identifiers only ever
    need underscores escaped -- no other LaTeX-special character appears in a variant name, a
    dataclass field name, or a type-annotation string in this codebase)."""
    return s.replace("_", r"\_")


def code(s: str) -> str:
    """`\\SOcode{<escaped s>}`, for a Python identifier (variant name, field name, ...)."""
    return r"\SOcode{" + esc(s) + "}"


def row(cells: list[str]) -> str:
    """One tabular data row: cells joined by ` & `, terminated with ` \\\\`."""
    return " & ".join(cells) + r" \\"


def multicol_note(ncols: int, text: str) -> str:
    return r"\multicolumn{" + str(ncols) + "}{l}{" + text + "}" + r" \\"


def fmt_tuple(values, spec: str = ".2f") -> str:
    return "(" + ", ".join(f"{v:{spec}}" for v in values) + ")"


def fmt_shape(shape) -> str:
    if shape is None:
        return "---"
    if len(shape) == 1:
        return f"({shape[0]},)"
    return "(" + ", ".join(str(s) for s in shape) + ")"


def fmt_signed(x: float, spec: str = ".4f") -> str:
    """`x` formatted to `spec`, with a "-0.0000"-shaped result stripped to "0.0000": a value that
    is zero only to floating-point epsilon (e.g. -2.2e-16) must not render as a *negative* zero,
    which reads as a sign the underlying quantity does not actually have."""
    s = f"{x:{spec}}"
    if s.startswith("-") and float(s) == 0.0:
        s = s[1:]
    return s


def ceil_pow10_label(x: float) -> str:
    """`x`'s magnitude as a power-of-ten ceiling, e.g. 3.2e-16 -> ``$<10^{-15}$``."""
    ax = abs(x)
    if ax == 0.0:
        return "$= 0$"
    e = math.ceil(math.log10(ax))
    return f"$<10^{{{e}}}$"


def macro(name: str, value: str) -> str:
    return r"\newcommand{\SOnum" + name + "}{" + value + "}"


def write_generated(path: Path, extra_header: list[str], body: list[str]) -> None:
    """Write `path` with the standard generated-file header, deterministically."""
    lines = [GENERATED_HEADER, *extra_header, *body]
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


