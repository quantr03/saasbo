_SLOPE_RATIO_N = 2000
_SLOPE_RATIO_SEED = 12345
_SLOPE_RATIO_GRID_N = 1024


def tab_slope_ratio(outdir: Path, stats: dict) -> None:
    ells = families_ell_set()
    grid = kernel.make_grid(0.0, 1.0, _SLOPE_RATIO_GRID_N)

    lines = [
        f"% N = {_SLOPE_RATIO_N} draws per ell, default_rng({_SLOPE_RATIO_SEED}) fresh per ell, "
        f"1024-point unit grid; SE = sample std / sqrt(N)",
        r"\begin{tabular}{rrrrr}",
        r"\toprule",
        row([r"$\ell$", r"$5/(3\ell^2\vell{\ell})$", "raw-draw mean $\\pm$ SE", "rescaled mean $\\pm$ SE",
             "ratio (rescaled/theory)"]),
        r"\midrule",
    ]
    for ell in ells:
        F = kernel.eigen_factor(0.0, 1.0, _SLOPE_RATIO_GRID_N, ell)
        rng = np.random.default_rng(_SLOPE_RATIO_SEED)
