def tab_npz_json_layout(outdir: Path, stats: dict) -> None:
    with tempfile.TemporaryDirectory(prefix="synthobj_npz_layout_") as tmp:
        tmp_path = Path(tmp)
        obj_a = make_family("interaction_g0.25", seed=0, D=20)
        obj_b = make_family("rotated_t45", seed=0, D=20)
        npz_a, json_a = obj_a.save(tmp_path / "interaction_g0.25")
        npz_b, json_b = obj_b.save(tmp_path / "rotated_t45")

        with np.load(npz_a) as da, np.load(npz_b) as db:
            names = sorted(set(da.files) | set(db.files))
            npz_rows = []
            for name in names:
                arr_a = da[name] if name in da.files else None
                arr_b = db[name] if name in db.files else None
                dtype_str = str(arr_a.dtype if arr_a is not None else arr_b.dtype)
                npz_rows.append((name, fmt_shape(None if arr_a is None else arr_a.shape),
                                  fmt_shape(None if arr_b is None else arr_b.shape), dtype_str))

        payload_a = json.loads(json_a.read_text())
        payload_b = json.loads(json_b.read_text())
        keys = sorted(set(payload_a) | set(payload_b))
        json_rows = []
        for key in keys:
            type_a = type(payload_a[key]).__name__ if key in payload_a else "---"
            type_b = type(payload_b[key]).__name__ if key in payload_b else "---"
            json_rows.append((key, type_a, type_b))

    lines = [
        r"\begin{tabular}{llll}",
        r"\toprule",
        row(["member/key", r"\SOcode{interaction\_g0.25}", r"\SOcode{rotated\_t45}", "dtype"]),
        r"\midrule",
        multicol_note(4, r"\textbf{npz members}"),
    ]
    for name, sa, sb, dt in npz_rows:
        lines.append(row([code(name), sa, sb, esc(dt)]))
    lines.append(r"\midrule")
    lines.append(multicol_note(4, r"\textbf{top-level JSON keys} (Python type of the stored value)"))
    for key, ta, tb in json_rows:
        lines.append(row([code(key), esc(ta), esc(tb), "---"]))
    # The rank-order-versus-coordinate-order note used to be a final \multicolumn{4}{l} row.
    # A `l` multicolumn cannot wrap, so that one sentence made the table 806pt wide against a
    # 345pt block -- 580pt of the overhang was the note alone (ruling R26, task-6 item 0f). It is
    # prose, not a measurement, so it now lives in A3's caption for this table, where it wraps;
    # A3's "Rank order versus coordinate order" paragraph states the same rule at length.
    lines += [r"\bottomrule", r"\end{tabular}"]
    write_generated(outdir / "tab_npz_json_layout.tex", [], lines)


