def generate_all(outdir: Path) -> None:
    outdir.mkdir(parents=True, exist_ok=True)
    stats: dict = {}
    total0 = time.perf_counter()
    for filename, fn in TABLE_REGISTRY:
        t0 = time.perf_counter()
        fn(outdir, stats)
        print(f"  {filename}: {time.perf_counter() - t0:.2f}s")
    print(f"regen_tables: {len(TABLE_REGISTRY)} file(s) written to {outdir} in {time.perf_counter() - total0:.2f}s")
    report_manifest_hash_match(get_grid100())


def _diff_files(committed: Path, fresh: Path) -> list[str]:
    a_lines = committed.read_text(encoding="utf-8").splitlines(keepends=True) if committed.exists() else []
    b_lines = fresh.read_text(encoding="utf-8").splitlines(keepends=True) if fresh.exists() else []
    return list(difflib.unified_diff(a_lines, b_lines, fromfile=str(committed), tofile=str(fresh)))


def run_check() -> int:
    diffed_names = [name for name, _fn in TABLE_REGISTRY if name != "tab_environment.tex"]
    with tempfile.TemporaryDirectory(prefix="synthobj_tables_check_") as tmp:
        tmp_path = Path(tmp)
        generate_all(tmp_path)
        mismatches = []
        for name in diffed_names:
            d = _diff_files(TABLES_DIR / name, tmp_path / name)
            if d:
                mismatches.append((name, d))

    if mismatches:
        for name, d in mismatches:
            print(f"=== {name} differs ===")
            sys.stdout.writelines(d)
        print(f"regen_tables --check: {len(mismatches)} of {len(diffed_names)} table(s) differ")
        return 1
    print(f"regen_tables --check: {len(diffed_names)} tables current")
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="regenerate into a temp dir and diff")
    args = parser.parse_args(argv)

    if args.check:
        return run_check()
    generate_all(TABLES_DIR)
    return 0


if __name__ == "__main__":
    sys.exit(main())
